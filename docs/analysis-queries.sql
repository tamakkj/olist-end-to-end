-- Q18. Which payment methods are most commonly used?
-- Answer: credit_card 73.92%, boleto 19.04%, voucher 5.56%, debit_card 1.47%
SELECT payment_type,
       COUNT(*) AS payment_records,
       ROUND(100.0 * COUNT(*) / SUM(COUNT(*)) OVER (), 2) AS pct_share,
       ROUND(AVG(payment_value), 2)                       AS avg_payment_value
FROM olist.silver.payments
GROUP BY payment_type
ORDER BY payment_records DESC;

-- Q19. What is the average payment value per order?
-- Answer: R$ 160.99 per order (R$ 154.10 per payment record — orders can split payments)
SELECT COUNT(DISTINCT order_id)                             AS orders_with_payments,
       ROUND(SUM(payment_value) / COUNT(DISTINCT order_id), 2) AS avg_payment_per_order,
       ROUND(AVG(payment_value), 2)                           AS avg_per_payment_record
FROM olist.silver.payments;

-- Q20. Which installment plans are most frequently selected?
-- Answer: 1x 50.58%, 2x 11.95%, 3x 10.07%, 4x 6.83%, 10x 5.13%
SELECT payment_installments,
       COUNT(*) AS payment_records,
       ROUND(100.0 * COUNT(*) / SUM(COUNT(*)) OVER (), 2) AS pct_share
FROM olist.silver.payments
GROUP BY payment_installments
ORDER BY payment_records DESC
LIMIT 12;