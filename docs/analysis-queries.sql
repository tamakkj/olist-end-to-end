-- ============================================================================
-- olist-end-to-end — Analysis queries
-- Every question answered in README.md, mapped to the SQL that answers it.
-- All metrics computed on the gold layer (catalog `olist`).
-- Business rules (Gold Layer Design Spec):
--   * Financial  = valid orders only   (order_status NOT IN ('canceled','unavailable'))
--   * Logistics  = delivered orders only
--   * Behavioral = all order statuses
--   * Monetary values in BRL (R$)
-- LIMIT clauses are presentation limits (top-N tables in the README).
-- ============================================================================

-- ============================================================================
-- SALES & ORDERS
-- ============================================================================

-- Q1. What is the total revenue generated by valid orders?
-- Answer: R$ 15,735,527.03 (items R$ 13,494,400.74 + freight R$ 2,241,126.29) across 98,207 valid orders
SELECT COUNT(*)                        AS valid_orders,
       ROUND(SUM(total_order_value), 2) AS revenue_valid_total,
       ROUND(SUM(total_items_price), 2)  AS revenue_items_valid,
       ROUND(SUM(total_freight_value), 2) AS freight_valid
FROM olist.gold.full_order
WHERE order_status NOT IN ('canceled', 'unavailable');

-- Q2. What is the average order value?
-- Answer: R$ 160.23 per valid order
SELECT ROUND(AVG(total_order_value), 2) AS avg_order_value
FROM olist.gold.full_order
WHERE order_status NOT IN ('canceled', 'unavailable');

-- Q3. How does order volume evolve over time?
-- Answer: steady growth through 2017, peak Nov 2017 (7,544 orders), stable ~6.2-7.3k/month in 2018
SELECT purchase_month,
       COUNT(*) AS orders,
       ROUND(SUM(CASE WHEN order_status NOT IN ('canceled', 'unavailable') THEN total_order_value END), 2) AS revenue_valid
FROM olist.gold.full_order
GROUP BY purchase_month
ORDER BY purchase_month;

-- Q4a. Which days of the week have the highest purchase activity?
-- Answer: Monday busiest (16,196), Saturday slowest (10,887)
SELECT purchase_weekday,
       COUNT(*) AS orders,
       ROUND(AVG(CASE WHEN order_status NOT IN ('canceled', 'unavailable') THEN total_order_value END), 2) AS avg_order_value
FROM olist.gold.full_order
GROUP BY purchase_weekday
ORDER BY orders DESC;

-- Q4b. Which hours have the highest purchase activity?
-- Answer: peak at 16h (6,675), plateau 10h-21h, minimum 2h-5h
SELECT purchase_hour,
       COUNT(*) AS orders
FROM olist.gold.full_order
GROUP BY purchase_hour
ORDER BY orders DESC;

-- Q5. What percentage of orders are canceled or unavailable?
-- Answer: 1.24% of all orders (625 canceled 0.63% + 609 unavailable 0.61% of 99,441)
SELECT COUNT(*)                            AS total_orders,
       COUNT_IF(order_status = 'canceled')    AS canceled_orders,
       COUNT_IF(order_status = 'unavailable') AS unavailable_orders,
       ROUND(100.0 * COUNT_IF(order_status = 'canceled')    / COUNT(*), 2) AS canceled_pct,
       ROUND(100.0 * COUNT_IF(order_status = 'unavailable') / COUNT(*), 2) AS unavailable_pct,
       ROUND(100.0 * COUNT_IF(order_status IN ('canceled', 'unavailable')) / COUNT(*), 2) AS invalid_pct
FROM olist.gold.full_order;

-- ============================================================================
-- CUSTOMER INSIGHTS
-- ============================================================================

-- Q6. How many customers have made repeat purchases?
-- Answer: 2,997 of 96,096 unique customers (3.12%)
SELECT COUNT(*)                     AS total_customers,
       COUNT_IF(is_repeat_customer) AS repeat_customers,
       ROUND(100.0 * COUNT_IF(is_repeat_customer) / COUNT(*), 2) AS repeat_pct
FROM olist.gold.dim_customers;

-- Q7. How much does each customer spend on average?
-- Answer: R$ 163.79 lifetime per customer; R$ 158.28 per order
SELECT ROUND(AVG(total_spent), 2)                   AS avg_lifetime_spent_per_customer,
       ROUND(SUM(total_spent) / SUM(order_count), 2) AS avg_spent_per_order
FROM olist.gold.dim_customers;

-- Q8a. Which states account for the largest share of customers?
-- Answer: SP 41.94%, RJ 12.88%, MG 11.71% (Southeast ~66%)
SELECT customer_state,
       COUNT(*) AS customers,
       ROUND(100.0 * COUNT(*) / SUM(COUNT(*)) OVER (), 2) AS pct_share
FROM olist.gold.dim_customers
GROUP BY customer_state
ORDER BY customers DESC
LIMIT 10;

-- Q8b. Which cities account for the largest share of customers?
-- Answer: Sao Paulo (14,977), Rio de Janeiro (6,615), Belo Horizonte (2,667)...
SELECT customer_city,
       customer_state,
       COUNT(*) AS customers
FROM olist.gold.dim_customers
GROUP BY customer_city, customer_state
ORDER BY customers DESC
LIMIT 10;

-- Q9. How many customers are associated with inconsistent location records?
-- Answer: 122 customers (0.13%)
SELECT COUNT(*)                       AS total_customers,
       COUNT_IF(location_inconsistent) AS location_inconsistent_customers,
       ROUND(100.0 * COUNT_IF(location_inconsistent) / COUNT(*), 2) AS inconsistent_pct
FROM olist.gold.dim_customers;

-- ============================================================================
-- PRODUCT PERFORMANCE
-- ============================================================================

-- Q10. Which product categories generate the most revenue?
-- Answer: health_beauty R$ 1,255,695.13, watches_gifts R$ 1,198,185.21, bed_bath_table R$ 1,035,964.06
-- (dim_products already applies the valid-orders financial rule)
SELECT COALESCE(product_category_name_english, 'uncategorized') AS category,
       ROUND(SUM(total_revenue), 2) AS revenue,
       SUM(ordered_count)           AS items_sold,
       SUM(unique_orders)           AS orders
FROM olist.gold.dim_products
GROUP BY 1
ORDER BY revenue DESC
LIMIT 10;

-- Q11. Which products have the highest sales volume?
-- Answer: top product aca2eb7d00ea1a7b8ebd4e68314663af with 527 items sold
SELECT product_id,
       ROUND(total_revenue, 2) AS revenue,
       ordered_count           AS items_sold,
       unique_orders           AS orders,
       ROUND(avg_price, 2)     AS avg_price
FROM olist.gold.dim_products
ORDER BY items_sold DESC
LIMIT 10;

-- Q12. What is the average selling price per product?
-- Answer: mean R$ 144.96, median R$ 79.00, range R$ 0.85 - R$ 6,735.00, 222 products never sold
SELECT ROUND(AVG(avg_price), 2)                                              AS avg_price_per_product,
       ROUND(percentile_cont(0.5) WITHIN GROUP (ORDER BY avg_price), 2)      AS median_price_per_product,
       ROUND(MIN(avg_price), 2)                                              AS min_price,
       ROUND(MAX(avg_price), 2)                                              AS max_price,
       COUNT_IF(avg_price IS NULL)                                           AS products_never_sold
FROM olist.gold.dim_products;

-- Q13. Which product categories receive the highest average review scores?
-- Answer: books_general_interest 4.45, books_technical 4.36, luggage_accessories 4.31
-- (item-level join so the score is order-weighted; min 100 reviewed orders)
SELECT COALESCE(p.product_category_name_english, 'uncategorized') AS category,
       ROUND(AVG(fo.review_score), 2) AS avg_review_score,
       COUNT(DISTINCT fo.order_id)     AS reviewed_orders
FROM olist.silver.order_items oi
JOIN olist.gold.full_order   fo USING (order_id)
JOIN olist.silver.products   p  USING (product_id)
WHERE fo.review_score IS NOT NULL
GROUP BY 1
HAVING reviewed_orders >= 100
ORDER BY avg_review_score DESC, reviewed_orders DESC
LIMIT 10;

-- ============================================================================
-- LOGISTICS & DELIVERY
-- ============================================================================

-- Q14. What is the average time between purchase and delivery?
-- Answer: 12.56 days (3.23 purchase->carrier + 9.33 carrier->customer)
SELECT ROUND(AVG(total_delivery_days), 2)      AS avg_delivery_days,
       ROUND(AVG(purchase_to_carrier_days), 2) AS avg_purchase_to_carrier_days,
       ROUND(AVG(carrier_to_customer_days), 2) AS avg_carrier_to_customer_days
FROM olist.gold.full_logistics;

-- Q15. What percentage of orders are delivered later than expected?
-- Answer: 8.11% of delivered orders (7,826 of 96,478)
SELECT COUNT(*)                  AS delivered_orders,
       COUNT_IF(is_late_delivery) AS late_deliveries,
       ROUND(100.0 * COUNT_IF(is_late_delivery) / COUNT(*), 2) AS late_pct
FROM olist.gold.full_logistics;

-- Q16. Which sellers have the highest late delivery rates?
-- Answer: b1b3948701c5c72445495bd161b83a4c (SP) 64.29% of 16 orders
-- (min 10 orders to filter out statistical noise; late_delivery_rate denominator = all statuses)
SELECT seller_id,
       seller_state,
       late_delivery_rate,
       order_count,
       ROUND(total_revenue, 2) AS revenue
FROM olist.gold.dim_sellers
WHERE order_count >= 10
ORDER BY late_delivery_rate DESC, order_count DESC
LIMIT 10;

-- Q17a. What is the average freight cost per seller? (distribution)
-- Answer: mean R$ 23.44, median R$ 18.24, range R$ 1.20 - R$ 308.34
SELECT COUNT(*)                                                        AS sellers,
       ROUND(AVG(avg_freight_value), 2)                                AS avg_freight_per_seller,
       ROUND(percentile_cont(0.5) WITHIN GROUP (ORDER BY avg_freight_value), 2) AS median_freight_per_seller,
       ROUND(MIN(avg_freight_value), 2)                                AS min_freight,
       ROUND(MAX(avg_freight_value), 2)                                AS max_freight
FROM olist.gold.dim_sellers
WHERE avg_freight_value IS NOT NULL;

-- Q17b. Sellers with the highest average freight (context for Q17a)
-- Answer: top seller 6fa9202c10491e472dffd59a3e82b2a3 at R$ 308.34 (3 items sold)
SELECT seller_id,
       ROUND(avg_freight_value, 2) AS avg_freight_value,
       total_items_sold,
       ROUND(total_revenue, 2)      AS revenue
FROM olist.gold.dim_sellers
WHERE avg_freight_value IS NOT NULL
ORDER BY avg_freight_value DESC
LIMIT 5;

